#!/usr/bin/env python3
"""Emit typed C calls and Scheme registry from the reviewed stage-1 projection.

shapes.json records the source inventory and finite ABI fixture additions.
No runtime C compilation, libffi, or ABI-erasing dispatch is used.
"""
import json
from pathlib import Path
root = Path(__file__).resolve().parent
shapes = json.loads((root / 'shapes.json').read_text())['shapes']
types = {
    'int': ('int', 'int'), 'integer-8': ('int8_t', 'int8'),
    'unsigned-8': ('uint8_t', 'unsigned-int8'),
    'integer-16': ('int16_t', 'int16'), 'unsigned-16': ('uint16_t', 'unsigned-int16'),
    'integer-32': ('int32_t', 'int32'), 'unsigned-32': ('uint32_t', 'unsigned-int32'),
    'integer-64': ('int64_t', 'int64'), 'unsigned-64': ('uint64_t', 'unsigned-int64'),
    'size_t': ('size_t', 'size_t'), 'ssize_t': ('ssize_t', 'ssize_t'),
    'unsigned-long': ('unsigned long', 'unsigned-long'),
    'void*': ('void *', 'unsigned-long'), 'void': ('void', 'void'),
    'string': ('char *', 'UTF-8-string'), 'float': ('float', 'float32'),
    'double': ('double', 'float64'),
}
c = [';; GENERATED by generate-shims.py; edit shapes.json and regenerate.', '(c-declare #<<SHIMS']
scheme = []; entries = []; seen = set()
for i, shape in enumerate(shapes):
    args, ret, cap, var = (shape[k] for k in ('args', 'ret', 'capture', 'varargs'))
    key = (tuple(args), ret, cap, var)
    assert key not in seen, key
    seen.add(key)
    assert var is None or 0 < var <= len(args)
    name = f'joltffi_generated_{i}'
    params = ['unsigned long fn'] + (['unsigned long errout'] if cap else [])
    params += [f'{("unsigned long" if t == "void*" else types[t][0])} a{n}' for n,t in enumerate(args)]
    target_types = [types[t][0] for t in args]
    if var is not None: target_types = target_types[:var] + ['...']
    signature = ', '.join(target_types) or 'void'
    result = types[ret][0]
    wire_result = 'unsigned long' if ret == 'void*' else result
    call = 'f(' + ', '.join(('(void *)' if t == 'void*' else '') + f'a{n}' for n,t in enumerate(args)) + ')'
    c += [f'/* {shape["id"]}: variadic boundary {var}, capture {cap} */',
          f'static {wire_result} {name}({", ".join(params)})', '{',
          f'  {result} (*f)({signature}) = ({result} (*)({signature}))fn;']
    if ret == 'void': c += [f'  {call};']
    else: c += [f'  {result} r = {call};']
    if cap:
        c += ['  int saved = errno;', '  *(int *)errout = saved;',
              '#ifdef JOLTFFI_CAPTURE_TEST', '  errno = 4242; /* after capture, before Gambit conversion */', '#endif']
    if ret != 'void': c += [('  return (unsigned long)r;' if ret == 'void*' else '  return r;')]
    c += ['}']
    scargs = ['fn'] + (['errout'] if cap else []) + [f'a{n}' for n in range(len(args))]
    ctypes = ['unsigned-long'] * (2 if cap else 1) + [types[t][1] for t in args]
    scheme += [f'(define (joltffi-shim-{i} {" ".join(scargs)})',
               f'  ((c-lambda ({" ".join(ctypes)}) {types[ret][1]} "{name}") {" ".join(scargs)}))']
    entries += [f'    (list \'({" ".join(args)}) \'{ret} {"#t" if cap else "#f"} {"#f" if var is None else var} joltffi-shim-{i})']
c += ['SHIMS', ')']
output = '\n'.join(c + scheme + ['(define joltffi-shims', '  (list'] + entries + ['))', '''(define (joltffi-shim-lookup args ret capture? variadic)
  (let loop ((es joltffi-shims))
    (if (null? es) #f
        (let ((e (car es)))
          (if (and (equal? args (car e)) (eq? ret (cadr e))
                   (eq? capture? (caddr e)) (equal? variadic (cadddr e)))
              (car (cddddr e))
              (loop (cdr es)))))))''']) + '\n'
import sys
if '--check' in sys.argv:
    if (root / 'generated-shims.scm').read_text() != output:
        raise SystemExit('generated-shims.scm is stale')
else:
    (root / 'generated-shims.scm').write_text(output)
