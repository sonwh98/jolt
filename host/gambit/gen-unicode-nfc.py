#!/usr/bin/env python3
"""Emit Gambit's canonical normalization tables using Python's Unicode 16.0 data."""
import unicodedata as u

if u.unidata_version != "16.0.0":
    raise SystemExit(f"Unicode 16.0.0 required, found {u.unidata_version}")

decompositions = []
compositions = []
classes = []
for cp in range(0x110000):
    char = chr(cp)
    combining_class = u.combining(char)
    if combining_class:
        classes.append(f"({cp} . {combining_class})")
    if 0xAC00 <= cp <= 0xD7A3:  # Hangul decomposes algorithmically.
        continue
    mapping = u.decomposition(char)
    if mapping and not mapping.startswith("<"):
        parts = [int(part, 16) for part in mapping.split()]
        decompositions.append(f"({cp} {' '.join(map(str, parts))})")
        if len(parts) == 2 and u.normalize("NFC", "".join(map(chr, parts))) == char:
            key = parts[0] * 0x110000 + parts[1]
            compositions.append(f"({key} . {cp})")

print(";; Unicode 16.0.0 canonical normalization data.")
print(";; Generated by gen-unicode-nfc.py. See licenses/Unicode-3.0.txt.")
for name, rows in (("nfc-classes", classes),
                   ("nfc-decompositions", decompositions),
                   ("nfc-compositions", compositions)):
    print(f"(define {name}")
    print("  (list->table '(")
    for offset in range(0, len(rows), 4):
        print("    " + " ".join(rows[offset:offset + 4]))
    print("  ) test: eqv?))")
